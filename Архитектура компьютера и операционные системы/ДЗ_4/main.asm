
# main.asm - Основная программа вычисления квадратного корня

# Подключаем файл с макроопределениями
.include "macros.asm"

.text
.globl main

# Основная точка входа программы
main:
    # Чтение числа от пользователя
    read_float(enter_num_msg, fs0)  # Вызов макроса для ввода числа
                                    # enter_num_msg - приглашение для ввода числа
                                    # fs0 - регистр для сохранения введенного числа
    fmv.s fs0, fa0                  # Сохраняем введенное число в fs0 для дальнейшего использования
    
    # Чтение точности вычислений от пользователя
    read_float(enter_prec_msg, fs1) # Вызов макроса для ввода точности
                                    # enter_prec_msg - приглашение для ввода точности
                                    # fs1 - регистр для сохранения точности
    fmv.s fs1, fa0                  # Сохраняем точность в fs1 для дальнейшего использования
    
    # Проверка корректности введенных данных
    check_positive(fs0, fs1, invalid_input)
                                    # Проверяем, что число и точность положительные
                                    # fs0 - регистр с числом
                                    # fs1 - регистр с точностью  
                                    # invalid_input - метка для перехода при ошибке
    
    # Вычисление квадратного корня
    compute_sqrt(fs0, fs1, fs2)     # Вызов макроса для вычисления квадратного корня
                                    # fs0 - число для извлечения корня
                                    # fs1 - требуемая точность вычислений
                                    # fs2 - регистр для результата
    fmv.s fs2, fa0                  # Сохраняем результат вычислений в fs2
    
    # Вывод результата на экран
    print_result(fs2, result_msg)   # Вызов макроса для вывода результата
                                    # fs2 - регистр с вычисленным корнем
                                    # result_msg - сообщение для вывода перед результатом
    
    j finish                        # Переход к корректному завершению программы

# Обработчик некорректного ввода
invalid_input:
    la a0, error_msg                # Загружаем адрес сообщения об ошибке
    li a7, 4                        # Код системного вызова для печати строки
    ecall                           # Выводим сообщение об ошибке

# Корректное завершение программы
finish:
    li a7, 10                       # Код системного вызова для завершения программы
    ecall                           # Завершаем выполнение программы

# Подключаем файл с реализацией алгоритма вычисления квадратного корня
.include "sqrt.asm"
